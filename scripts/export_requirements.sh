#!/usr/bin/env bash
# scripts/export_requirements.sh — Regenerate the committed requirements.txt
# from pyproject.toml + uv.lock (the single source of truth).
#
# requirements.txt is an ARTIFACT, not an input:
#   * Databricks Apps installs a root requirements.txt at deploy time, and a
#     requirements.txt always takes precedence over pyproject/uv.lock there.
#   * The Databricks Asset Bundle regenerates it before every `bundle deploy`
#     (artifacts.python_requirements in databricks.yml).
#
# Output is deterministic: `uv export` is written to stdout (so its own header
# cannot embed a temporary path) and our fixed header is prepended.  CI runs
# this script and fails when the result differs from the committed file.
#
# Usage:
#   ./scripts/export_requirements.sh            # writes ./requirements.txt
#   ./scripts/export_requirements.sh /tmp/req   # writes elsewhere
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUT="${1:-$REPO_ROOT/requirements.txt}"
TMP="$(mktemp "${TMPDIR:-/tmp}/qp1-requirements.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

cd "$REPO_ROOT"

# --frozen: fail instead of silently re-locking; the committed uv.lock wins.
# --no-dev: runtime group only (what Databricks Apps needs).
uv export --frozen --no-dev --no-hashes > "$TMP"

{
  printf '%s\n' \
    '# requirements.txt — GENERATED by uv export from pyproject.toml + uv.lock — do not edit.' \
    '#' \
    '# Regenerate with: ./scripts/export_requirements.sh' \
    '# Source of truth: pyproject.toml [project].dependencies + uv.lock.' \
    '# CI fails when this file drifts from the lock (.github/workflows/ci.yml).' \
    '# Databricks Apps installs this file (pip) at deploy time.' \
    ''
  cat "$TMP"
} > "$OUT"

echo "wrote $OUT ($(grep -c '==' "$OUT" || true) pinned distributions)"
