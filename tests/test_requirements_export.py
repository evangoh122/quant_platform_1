"""The committed requirements.txt is a generated uv export, not a hand-edited file.

Databricks Apps installs the root requirements.txt when present (a
requirements.txt takes precedence over pyproject.toml/uv.lock), so it must stay
an exact, fully-pinned export of the locked runtime group. CI regenerates it and
fails on any diff; these offline tests fail fast when someone hand-edits it.
"""
from __future__ import annotations

import re
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = REPO_ROOT / "requirements.txt"
PYPROJECT = REPO_ROOT / "pyproject.toml"
LOCK = REPO_ROOT / "uv.lock"


def _requirement_lines() -> list[str]:
    return [
        line.strip()
        for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]


def test_requirements_header_marks_it_generated():
    first = REQUIREMENTS.read_text(encoding="utf-8").splitlines()[0]
    assert "GENERATED by uv export" in first
    assert "do not edit" in first.lower()
    assert "./scripts/export_requirements.sh" in REQUIREMENTS.read_text(encoding="utf-8")


def test_every_requirement_is_exactly_pinned():
    lines = _requirement_lines()
    assert len(lines) > 50, "runtime export looks truncated"
    for line in lines:
        assert "==" in line, f"unpinned requirement in a uv export: {line}"
        assert not re.match(r"^[A-Za-z0-9_.\-\[\]]+\s*[><~!]", line), (
            f"range specifier leaked into the generated export: {line}"
        )


def test_export_excludes_dev_only_and_pypi_unavailable_packages():
    names = {
        re.split(r"[\[=; ]", line)[0].strip().lower()
        for line in _requirement_lines()
    }
    # ibapi is not on PyPI; conftest stubs it. It must never be exported.
    assert "ibapi" not in names
    # Dev tooling must not be installed by Databricks Apps.
    for dev_only in ("pytest", "pip-audit", "evidently", "mlflow"):
        assert dev_only not in names, f"{dev_only} leaked into the runtime export"


def test_lockfile_and_declared_runtime_dependencies_exist():
    assert LOCK.exists(), "uv.lock must be committed"
    lock = LOCK.read_text(encoding="utf-8")
    assert 'version = 1' in lock
    assert 'name = "quant-platform"' in lock, "uv.lock must describe this project"
    data = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    deps = data["project"]["dependencies"]
    assert deps, "pyproject [project].dependencies must not be empty"
    assert data["project"]["requires-python"] == ">=3.12,<3.13"
    # Every declared runtime distribution appears in the generated export.
    exported = {
        re.split(r"[\[=; ]", line)[0].strip().lower()
        for line in _requirement_lines()
    }
    for spec in deps:
        dist = re.split(r"[\[<>=;!~ ]", spec)[0].strip().lower()
        assert dist in exported, f"{dist} declared in pyproject but missing from the export"


EXPORT_SCRIPT = REPO_ROOT / "scripts" / "export_requirements.sh"


def test_export_script_verifies_the_lock_before_exporting():
    """A stale uv.lock must fail the deploy-time export loudly.

    `uv export --frozen` refuses to re-lock but still exports whatever the
    committed lock contains, so a lock that no longer matches pyproject.toml
    would silently ship the old resolution through `bundle deploy`. The script
    therefore runs `uv lock --check` first and prints a clear message. The exit
    codes on a stale and an unchanged tree are exercised on a git-archive copy
    in the build evidence; this test pins the ordering offline.
    """
    script = EXPORT_SCRIPT.read_text(encoding="utf-8")
    code = [
        line.strip()
        for line in script.splitlines()
        if not line.lstrip().startswith("#")
    ]
    check = [i for i, line in enumerate(code) if "uv lock --check" in line]
    export = [i for i, line in enumerate(code) if "uv export --frozen" in line]
    assert len(check) == 1, "the export script must run `uv lock --check` exactly once"
    assert len(export) == 1, "the export script must run `uv export --frozen` exactly once"
    assert check[0] < export[0], "`uv lock --check` must run before the export"
    assert "uv.lock is out of date with pyproject.toml" in script, (
        "a stale lock must fail with an explicit message naming pyproject.toml"
    )


def test_dev_group_carries_the_evidently_pin_from_the_parallel_branch():
    data = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    dev = data["dependency-groups"]["dev"]
    assert "evidently==0.7.23" in dev, (
        "keep the exact evidently pin agreed with chore/evidently-drift-cleanup"
    )
